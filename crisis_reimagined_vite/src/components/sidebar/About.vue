  <h2 class="h4 mt-5">Futuring the public university through crisis </h2>
  <p>As an institution, the university is a perpetual crisis. Rather than only viewing crisis as a problem, we invite you to consider it as a necessary condition of the institution and to imagine how moments of disruption open possibilities to reimagine and remake the university we want.</p>
